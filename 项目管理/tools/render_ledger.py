def build_ledger():
    active = scan(TASKS); archived = scan(DONE); all_t = active + archived
    ready = compute_status(all_t)
    L = ["---","title: 任务账本","type: ledger","consumed_by: [编码 Agent, 项目负责人]",
         "note: 派生视图·勿手改，真相源在 tasks/*.md；跑 render_ledger.py render 重生成","---","",
         "# 任务账本","",
         "> ⚙️ **本文件由 `tools/render_ledger.py render` 自动生成，请勿手改；改任务只改 `tasks/T-*.md` 再 render。**",
         f"> 真相源 = `tasks/*.md` frontmatter。刷新 {datetime.now(CST):%Y-%m-%d %H:%M} · 活跃 {len(active)} / 已归档 {len(archived)}。",
         "> 生成 `... render` · 满里程碑归档 `... archive` · 派生父状态/依赖+就绪集 `... status`","",
         "## 里程碑视图","","| 里程碑 | 目标 | 覆盖层 | 完成 |","|---|---|---|---|"]
    for mid, name, goal in MILESTONES:
        tms = [t for t in all_t if t["milestone"] == mid]
        done = sum(1 for t in tms if t["status"] == "done")
        lset = sorted({layer_of(t["id"]) for t in tms}, key=lambda c: LAYER_ORDER.get(c,99))
        rng = (f"{lset[0]}–{lset[-1]}" if len(lset) > 1 else (lset[0] if lset else "—"))
        mark = "✅ " if tms and done == len(tms) else ""
        L.append(f"| {mid} · {name} | {goal} | {rng} | {mark}{done}/{len(tms)} |")
    L += ["", "## 依赖主轴（自底向上实现顺序）","",
          "`01 契约 → L0 → L1 → L2 → L3 → UI → L4 → ECO →（并行 L5）→ L6`；跨层一律经 `01-平台共享契约`，仅向下依赖。","",
          "## 就绪集（可开工 · todo 且依赖全 done）",""]
    if ready:
        for t in sorted(ready, key=ready_sort_key):
            L.append(f"- [`{t['id']}`]({t['rel']}) · {t['title']}（{t['priority']} / {t['milestone']}）")
    else: L.append("- （空）")
    L += ["","---",""]
    for code, head, story, mtag in LAYERS:
        rows = sorted([t for t in active if layer_of(t["id"]) == code], key=lambda x:x["id"])
        if not rows: continue
        L += [f"## {head}（{story}）｜{mtag}","",
              "| id | title | P | milestone | depends_on | status | arch |","|---|---|---|---|---|---|---|"]
        for t in rows:
            archcell = t["arch_link"].replace("../../docs/", "../docs/")   # 账本在 项目管理/ 层
            L.append(f"| [`{t['id']}`]({t['rel']}) | {t['title']} | {t['priority']} | {t['milestone']} | "
                     f"{', '.join(t['depends_on']) or '—'} | {t['status']} | {archcell} |")
        L.append("")
    if archived:
        L += ["## 已归档（里程碑完成）",""]
        for mid,*_ in MILESTONES:
            ids = sorted(t["id"] for t in archived if t["milestone"] == mid)
            if ids: L.append(f"- **{mid}** ✅ {len(ids)} 个 → `tasks/done/{mid}/`：{', '.join(ids)}")
        L.append("")
    text = "\n".join(L).rstrip() + "\n"
    return text, len(active), len(archived), len(ready)

def render():
    text, na, nr, nready = build_ledger()
    write_file(LEDGER, text)
    print(f"render: active {na}, archived {nr}, ready {nready} → 任务账本.md")

