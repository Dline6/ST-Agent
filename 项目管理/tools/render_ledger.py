def read_fm(path):
    lines = open(path, encoding="utf-8").read().splitlines()
    if not lines or lines[0].strip() != "---":
        return None, ""
    fm, i = {}, 1
    while i < len(lines) and lines[i].strip() != "---":
        if ":" in lines[i]:
            k, v = lines[i].split(":", 1)
            v = v.strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":  # 去成对引号
                v = v[1:-1]
            fm[k.strip()] = v
        i += 1
    return fm, "\n".join(lines[i+1:]).strip("\n")

def fm_list(fm, key):
    v = (fm.get(key, "") or "").strip()
    if not v or v in ("[]", "—", "-", "null"): return []
    return [x.strip() for x in v.strip("[]").split(",") if x.strip()]

def serialize(fm, body):
    """回写任务文件：已知字段按固定序 → 未知字段原序追加；空值字段保留。

    保真约定（2026-09-26）：派生父状态会重写任务文件，因此这里**不得丢字段**——
    工具不认识的自定义键、以及 `verify:` 这类空值键一律原样保留；仅改要改的值。
    """
    order = ["id","parent","title","story","arch","arch_link","priority","milestone",
             "depends_on","status","decisions","verify"]
    keys = [k for k in order if k in fm] + [k for k in fm if k not in order]
    out = ["---"]
    for k in keys:
        v = fm[k]
        if v == "":
            out.append(f"{k}:")                       # 空值保留（read_fm 解析为空串）
        elif k == "arch_link":
            out.append(f'{k}: "{v}"')
        else:
            out.append(f"{k}: {v}")
    out += ["---", "", body]
    return "\n".join(out).rstrip() + "\n"

def write_file(path, text):
    """写文本文件，**强制 LF**（2026-09-26）。

    Windows 文本模式默认把 ``\\n`` 翻成 ``\\r\\n``；本目录的写入口（bootstrap /
    派生父状态 / 账本渲染 / verify_docs --fix）若不锁定换行符，就会在盘上留下
    CRLF，与仓库其余 LF 文件不一致——此后任何编辑都会产生整文件 diff。
    """
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def scan(root):
    res = []
    for dp, subdirs, fs in os.walk(root):
        if os.path.abspath(dp) == os.path.abspath(TASKS):
            subdirs[:] = [d for d in subdirs if d != "done"]
        for fn in fs:
            if not fn.endswith(".md") or fn.startswith("_"): continue
            path = os.path.join(dp, fn)
            fm, _ = read_fm(path)
            if not fm or not fm.get("id"): continue
            par = (fm.get("parent", "") or "").strip()
            res.append(dict(
                id=fm["id"], title=fm.get("title",""), arch_link=fm.get("arch_link", fm["id"]),
                priority=fm.get("priority",""), milestone=fm.get("milestone",""),
                status=fm.get("status","todo"), depends_on=fm_list(fm,"depends_on"),
                parent=(par if par not in ("null","—","-") else ""),
                rel=os.path.relpath(path, PM).replace("\\","/"), path=path))
    return res

