def _norm(p): return os.path.normpath(p).replace("\\", "/")

def _link_path(raw):
    """``](raw)`` 的**路径**部分；非相对链接（锚点 / 协议 / 绝对路径）→ ``None``。

    与 ``verify_docs.link_target`` 同口径（去引号与 ``<>``、切掉 ``#``/``?`` 片段），
    这样「改写」与「校验」看的是同一批链接。
    """
    t = raw.strip().strip('"')
    if not t or t.startswith(NON_REL_PREFIX): return None
    t = t.split()[0].strip('<>').strip('"\'').split('#', 1)[0].split('?', 1)[0].strip()
    if not t or t.startswith(('/', '\\\\')): return None
    return t

def _retarget(text, here, candidates):
    """把 ``](target)`` 重定向到**首个存在**的候选路径（相对 ``here`` 输出）。

    :param here: 本文件所在目录（绝对）
    :param candidates: ``path -> [绝对路径, ...]``；按序取首个 ``exists`` 的。
        全部不存在 → 原样保留（留给 ``verify_docs`` 报断链，不静默猜）。

    三条约定：① 围栏代码段不动（同 ``verify_docs.strip_code`` 的范围）；
    ② 目标按原链接**仍可解析**时不动（幂等，重跑安全）；③ 只改 ``](...)`` 里的
    路径，正文其余部分逐字节不变。
    """
    def fix_seg(seg):
        def sub(m):
            head, raw, tail = m.group(1), m.group(2), m.group(3)
            p = _link_path(raw)
            if p is None: return m.group(0)
            for full in candidates(p):
                if os.path.exists(full):
                    rel = _norm(os.path.relpath(full, here))
                    if rel == _norm(p): return m.group(0)       # 仍成立 → 不动
                    frag = "#" + raw.split("#", 1)[1] if "#" in raw else ""
                    return f"{head}{rel}{frag}{tail}"
            return m.group(0)
        return MD_LINK.sub(sub, seg)
    return "".join(seg if i % 2 else fix_seg(seg) for i, seg in enumerate(FENCE.split(text)))

def _md_files():
    """仓库内全部 ``.md``（跳过 ``.git`` / 缓存 / 临时草稿目录，同断链扫描口径）。"""
    for dp, ds, fs in os.walk(ROOT):
        ds[:] = [d for d in ds if d not in SKIP_DIRS]
        for fn in sorted(fs):
            if fn.endswith(".md"):
                yield os.path.join(dp, fn)

def _rewrite_after_move(mid, moved):
    """移动后改正受影响链接（``archive`` 的第二步；只此一处做链接改写）。

    - **批内文件**：链接要么指向「同批一起搬走的邻居」（现为同目录），要么指向
      「没搬走的文件」（只多深了两层）。两种都由候选表按存在性判定，不靠数 ``../``。
    - **其余文件**：只改那些确实落在本批文件上的链接（指向别处的分毫不动）。
    """
    new_paths = {os.path.abspath(n) for _o, n in moved}
    dest = os.path.join(DONE, mid)

    def fix(full, cands):
        text = open(full, encoding="utf-8").read()
        fixed = _retarget(text, os.path.dirname(full), cands)
        if fixed != text: write_file(full, fixed)

    for _old, new in moved:                      # ① 批内文件自身
        here = os.path.dirname(new)
        fix(new, lambda p, here=here: [
            os.path.join(here, p),                                    # 仍成立（幂等）
            os.path.join(here, os.path.basename(p.rstrip("/"))),      # 同批一起搬走
            os.path.join(TASKS, p),                                   # 只是深了两层
        ])
    for full in _md_files():                     # ② 全仓其余 .md
        if os.path.abspath(full) in new_paths: continue
        if os.path.abspath(full) == os.path.abspath(LEDGER): continue  # 派生视图，render 重生
        here = os.path.dirname(full)
        fix(full, lambda p, here=here: [
            os.path.join(here, p),                                    # 仍成立（幂等）
            os.path.join(dest, os.path.basename(p.rstrip("/"))),      # 目标搬进了本批
        ])

def archive(dry):
    compute_status(scan(TASKS) + scan(DONE))
    for mid, *_ in MILESTONES:
        tms = [t for t in scan(TASKS) if t["milestone"] == mid]
        if tms and all(t["status"] == "done" for t in tms):
            print(f"{'DRY ' if dry else ''}archive {mid}: {len(tms)} → tasks/done/{mid}/")
            if dry: continue
            os.makedirs(os.path.join(DONE, mid), exist_ok=True)
            moved = [(t["path"], os.path.join(DONE, mid, os.path.basename(t["path"])))
                     for t in tms]
            for old, new in moved:
                shutil.move(old, new)
            _rewrite_after_move(mid, moved)
            render()                             # 账本随移动重生，收工时不必再跑 render

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["bootstrap","render","archive","status"])
    ap.add_argument("--dry", action="store_true"); ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    if a.cmd == "bootstrap": bootstrap(force=a.force)
    elif a.cmd == "render": render()
    elif a.cmd == "archive": archive(a.dry)
    else: print("ready:", [t["id"] for t in compute_status(scan(TASKS)+scan(DONE))])

if __name__ == "__main__": main()
